import { chromium } from 'playwright';
const browser = await chromium.connectOverCDP('http://localhost:29229');
const ctx = browser.contexts()[0] || await browser.newContext();
const page = await ctx.newPage();
const svg = process.argv[2];
const out = process.argv[3];
const size = parseInt(process.argv[4] || '512');
await page.setContent(`<body style="margin:0;background:#222;display:flex;align-items:center;justify-content:center;height:100vh">${svg}</body>`);
await page.setViewportSize({ width: size, height: size });
await page.locator('svg').first().screenshot({ path: out });
await page.close(); await browser.close();
console.log(out);
