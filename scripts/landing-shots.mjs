import { chromium } from 'playwright';
const browser = await chromium.connectOverCDP('http://localhost:29229');
const ctx = browser.contexts()[0] || await browser.newContext();
const page = await ctx.newPage();
await page.setViewportSize({ width: 1280, height: 900 });
await page.goto('http://localhost:3100/', { waitUntil: 'domcontentloaded' });
await page.evaluate(async () => {
  const regs = await navigator.serviceWorker?.getRegistrations() ?? [];
  await Promise.all(regs.map(r => r.unregister()));
  await Promise.all((await caches.keys()).map(k => caches.delete(k)));
});
await page.goto('http://localhost:3100/', { waitUntil: 'networkidle' });
await page.waitForTimeout(2500);
await page.screenshot({ path: '/home/ubuntu/landing-shots/landing-hero.png' });
await page.evaluate(() => window.scrollTo(0, document.querySelector('#inside-title')?.offsetTop - 40 || 2000));
await page.waitForTimeout(900);
await page.screenshot({ path: '/home/ubuntu/landing-shots/landing-inside.png' });
await page.evaluate(() => window.scrollTo(0, document.querySelector('#pricing')?.offsetTop - 20 || 4000));
await page.waitForTimeout(900);
await page.screenshot({ path: '/home/ubuntu/landing-shots/landing-pricing.png' });
await page.screenshot({ path: '/home/ubuntu/landing-shots/landing-full.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://localhost:3100/', { waitUntil: 'networkidle' });
await page.waitForTimeout(2000);
await page.screenshot({ path: '/home/ubuntu/landing-shots/landing-mobile.png' });
await page.close();
await browser.close();
