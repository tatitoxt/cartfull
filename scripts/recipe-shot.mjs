import { chromium } from 'playwright';
const BASE = 'http://localhost:3100';
const browser = await chromium.connectOverCDP('http://localhost:29229');
const ctx = browser.contexts()[0] || await browser.newContext();
const page = await ctx.newPage();
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(BASE + '/app/recipe/slow-cooker-pulled-pork', { waitUntil: 'networkidle' });
await page.waitForTimeout(2500);
console.log(page.url());
await page.screenshot({ path: '/home/ubuntu/landing-shots/recipe.png' });
await page.goto(BASE + '/app/list', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
const link = await page.locator('a[href*="/app/recipe/"]').first().getAttribute('href').catch(()=>null);
console.log('recipe link from list', link);
await page.close();
await browser.close();
