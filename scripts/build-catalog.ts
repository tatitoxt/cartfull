/**
 * Merges data/ingredients*.json and data/recipes/*.json into the bundle the app
 * imports (lib/catalog/catalog.generated.json) and the database seed (db/seed.sql).
 * Usage: npm run catalog:build
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Ingredient, Recipe } from "../lib/catalog/types";

const root = join(__dirname, "..");
const dataDir = join(root, "data");
const readJson = <T>(path: string): T => JSON.parse(readFileSync(path, "utf8")) as T;

const ingredients = readdirSync(dataDir)
  .filter((f) => /^ingredients.*\.json$/.test(f))
  .sort()
  .flatMap((f) => readJson<Ingredient[]>(join(dataDir, f)));

const recipes = readdirSync(join(dataDir, "recipes"))
  .filter((f) => f.endsWith(".json"))
  .sort()
  .flatMap((f) => readJson<Recipe[]>(join(dataDir, "recipes", f)))
  .sort((a, b) => a.slug.localeCompare(b.slug));

writeFileSync(
  join(root, "lib", "catalog", "catalog.generated.json"),
  JSON.stringify({ ingredients, recipes }) + "\n",
);

const q = (value: string) => `'${value.replace(/'/g, "''")}'`;
const arr = (values: string[]) => (values.length ? `array[${values.map(q).join(", ")}]::text[]` : "'{}'::text[]");

const lines: string[] = [
  "-- Generated by `npm run catalog:build`. Do not edit by hand.",
  "-- Safe to run again: existing rows are updated in place.",
  "begin;",
  "",
];

lines.push(
  "insert into public.ingredients (id, name, aisle, unit, pkg_qty, pkg_cents, pkg_label, kind, staple, spicy, allergens) values",
  ingredients
    .map(
      (i) =>
        `  (${q(i.id)}, ${q(i.name)}, ${q(i.aisle)}, ${q(i.unit)}, ${i.pkg_qty}, ${i.pkg_cents}, ${q(i.pkg_label)}, ${q(i.kind)}, ${i.staple}, ${i.spicy}, ${arr(i.allergens)})`,
    )
    .join(",\n"),
  "on conflict (id) do update set name = excluded.name, aisle = excluded.aisle, unit = excluded.unit,",
  "  pkg_qty = excluded.pkg_qty, pkg_cents = excluded.pkg_cents, pkg_label = excluded.pkg_label,",
  "  kind = excluded.kind, staple = excluded.staple, spicy = excluded.spicy, allergens = excluded.allergens;",
  "",
);

if (recipes.length) {
  lines.push(
    "insert into public.recipes (slug, name, meal_type, diet_tags, servings, prep_minutes, batch_friendly, description, steps, photo_url, photo_credit_name, photo_credit_url, active) values",
    recipes
      .map(
        (r) =>
          `  (${q(r.slug)}, ${q(r.name)}, ${q(r.meal_type)}, ${arr(r.diet_tags)}, ${r.servings}, ${r.prep_minutes}, ${r.batch_friendly}, ${q(r.description)}, ${arr(r.steps)}, ${q(r.photo_url)}, ${q(r.photo_credit.name)}, ${q(r.photo_credit.url)}, true)`,
      )
      .join(",\n"),
    "on conflict (slug) do update set name = excluded.name, meal_type = excluded.meal_type, diet_tags = excluded.diet_tags,",
    "  servings = excluded.servings, prep_minutes = excluded.prep_minutes, batch_friendly = excluded.batch_friendly,",
    "  description = excluded.description, steps = excluded.steps, photo_url = excluded.photo_url,",
    "  photo_credit_name = excluded.photo_credit_name, photo_credit_url = excluded.photo_credit_url, active = true;",
    "",
    // Recipes dropped from the catalog stay (old plans reference them) but stop being offered.
    `update public.recipes set active = false where slug not in (${recipes.map((r) => q(r.slug)).join(", ")});`,
    "",
    `delete from public.recipe_ingredients where recipe_slug in (${recipes.map((r) => q(r.slug)).join(", ")});`,
    "insert into public.recipe_ingredients (recipe_slug, ingredient_id, qty, note, position) values",
    recipes
      .flatMap((r) =>
        r.ingredients.map(
          (ri, index) => `  (${q(r.slug)}, ${q(ri.id)}, ${ri.qty}, ${ri.note ? q(ri.note) : "null"}, ${index})`,
        ),
      )
      .join(",\n") + ";",
    "",
  );
}

lines.push("commit;", "");
writeFileSync(join(root, "db", "seed.sql"), lines.join("\n"));
console.log(`Wrote ${ingredients.length} ingredients and ${recipes.length} recipes.`);
